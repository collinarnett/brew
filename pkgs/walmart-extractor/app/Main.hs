{-# LANGUAGE OverloadedStrings #-}

module Main (main) where

import Data.Text qualified as T
import Data.Text.IO qualified as TIO
import Network.HTTP.Client (newManager)
import Network.HTTP.Client.TLS (tlsManagerSettings)
import System.Exit (die)

import WalmartExtractor (DiscoveryError (..), Endpoints (..), discoverEndpoints)

main :: IO ()
main = do
  mgr <- newManager tlsManagerSettings
  result <- discoverEndpoints mgr
  case result of
    Left (HashNotFound op) ->
      die ("No hash found for operation " <> T.unpack op <> " in any scanned JS chunk")
    Right eps ->
      TIO.putStr (generateModule eps)

generateModule :: Endpoints -> T.Text
generateModule eps = T.unlines
  [ "-- GENERATED by walmart-extractor. Do not edit manually."
  , "{-# LANGUAGE OverloadedStrings #-}"
  , ""
  , "module Walmart.Internal.Endpoints"
  , "  ( purchaseHistory"
  , "  , getOrder"
  , "  ) where"
  , ""
  , "import Walmart.Internal.HTTP (Endpoint (..))"
  , ""
  , "purchaseHistory :: Endpoint"
  , "purchaseHistory = Endpoint"
  , "  { endpointUrl = " <> showText (epPurchaseHistory eps)
  , "  , endpointOperation = \"PurchaseHistoryV2\""
  , "  }"
  , ""
  , "getOrder :: Endpoint"
  , "getOrder = Endpoint"
  , "  { endpointUrl = " <> showText (epGetOrder eps)
  , "  , endpointOperation = \"getOrder\""
  , "  }"
  ]

showText :: T.Text -> T.Text
showText t = "\"" <> T.replace "\"" "\\\"" t <> "\""
